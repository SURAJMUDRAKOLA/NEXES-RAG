  "CHUNK_CONFIG = {",
  "    'pdf':   {'size': 512,  'overlap': 100},",
  "    'pptx':  {'size': 1024, 'overlap': 0 },  # 1 slide = 1 chunk always",
  "    'docx':  {'size': 512,  'overlap': 100},",
