  "}",
  "",
  "def chunk_document(content: list, doc_type: str) -> List[ChunkData]:",
  "    cfg = CHUNK_CONFIG.get(doc_type, {'size': 512, 'overlap': 100})",
  "    chunks = []",
  "    for item in content:",
  "        if item.content_type == 'table':",
  "            # Never split tables — whole table as one chunk in markdown",
  "            chunks.append(ChunkData(content=item.markdown_text,",
  "                modality='table', page_num=item.page_num, chunk_type='table'))",
  "        elif item.content_type == 'image':",
