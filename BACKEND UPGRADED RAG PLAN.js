// ── HELPERS ────────────────────────────────────────────────
const pb = () => new Paragraph({ children: [new PageBreak()] });
const sp = (before=120, after=80) => ({ before, after });

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: sp(400, 200),
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: ACCENT } },
    children: [new TextRun({ text, bold: true, size: 36, color: DARK, font: "Arial" })]
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: sp(280, 160),
    children: [new TextRun({ text, bold: true, size: 28, color: ACCENT, font: "Arial" })]
  });
}
function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: sp(200, 120),
    children: [new TextRun({ text, bold: true, size: 24, color: PURPLE, font: "Arial" })]
  });
}
function h4(text) {
  return new Paragraph({
    spacing: sp(160, 80),
    children: [new TextRun({ text, bold: true, size: 22, color: TEAL, font: "Arial" })]
  });
}
function p(text, color = MID_GRAY) {
  return new Paragraph({
    spacing: sp(60, 100),
    children: [new TextRun({ text, size: 22, font: "Arial", color })]
  });
}
function bullet(text, level = 0) {
  return new Paragraph({
    numbering: { reference: "bullets", level },
    spacing: sp(40, 40),
    children: [new TextRun({ text, size: 21, font: "Arial", color: MID_GRAY })]
  });
}
function numbered(text, level = 0) {
  return new Paragraph({
    numbering: { reference: "numbers", level },
    spacing: sp(40, 40),
    children: [new TextRun({ text, size: 21, font: "Arial", color: MID_GRAY })]
  });
}
function codeLine(text) {
  return new Paragraph({
    spacing: sp(10, 10),
    shading: { type: ShadingType.CLEAR, fill: "1A1A2E" },
    indent: { left: 280, right: 280 },
    children: [new TextRun({ text: text || " ", size: 18, font: "Courier New", color: "A5B4FC" })]
  });
}
function codeBlock(lines) { return lines.map(l => codeLine(l)); }

function infoBox(label, lines, fillColor = LIGHT_BG, accentColor = ACCENT) {
  const children = [
    new Paragraph({ spacing: sp(0,60), children: [new TextRun({ text: label, bold: true, size: 20, color: accentColor, font: "Arial" })] }),
    ...lines.map(l => new Paragraph({ spacing: sp(0,0), children: [new TextRun({ text: l, size: 19, color: MID_GRAY, font: "Arial" })] }))
  ];
  return new Table({
    width: { size: W, type: WidthType.DXA },
    columnWidths: [W],
    rows: [new TableRow({ children: [new TableCell({
      borders: { ...noBorders, left: { style: BorderStyle.THICK, size: 20, color: accentColor } },
      shading: { type: ShadingType.CLEAR, fill: fillColor },
      margins: { top: 120, bottom: 120, left: 240, right: 240 },
      width: { size: W, type: WidthType.DXA },
      children
    })] })]
  });
}

function twoCol(rows, h1t, h2t, w1 = 2800, w2 = 6560) {
  const hRow = new TableRow({ tableHeader: true, children: [h1t, h2t].map((t, i) => new TableCell({
    borders, width: { size: i===0 ? w1 : w2, type: WidthType.DXA },
    shading: { type: ShadingType.CLEAR, fill: DARK },
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({ children: [new TextRun({ text: t, bold: true, size: 19, color: "FFFFFF", font: "Arial" })] })]
  }))});
  const dataRows = rows.map(([c1, c2], i) => new TableRow({ children: [
    new TableCell({ borders, width: { size: w1, type: WidthType.DXA }, shading: { type: ShadingType.CLEAR, fill: i%2===0 ? "EEF2FF" : "FFFFFF" }, margins: { top: 80, bottom: 80, left: 120, right: 120 }, children: [new Paragraph({ children: [new TextRun({ text: c1, bold: true, size: 19, color: DARK, font: "Arial" })] })] }),
    new TableCell({ borders, width: { size: w2, type: WidthType.DXA }, shading: { type: ShadingType.CLEAR, fill: i%2===0 ? "EEF2FF" : "FFFFFF" }, margins: { top: 80, bottom: 80, left: 120, right: 120 }, children: [new Paragraph({ children: [new TextRun({ text: c2, size: 19, color: MID_GRAY, font: "Arial" })] })] }),
  ]}));
  return new Table({ width: { size: W, type: WidthType.DXA }, columnWidths: [w1, w2], rows: [hRow, ...dataRows] });
}

function threeCol(rows, h1t, h2t, h3t, w1=2000, w2=4000, w3=3360) {
  const hRow = new TableRow({ tableHeader: true, children: [h1t,h2t,h3t].map((t,i)=> new TableCell({
    borders, width: { size: [w1,w2,w3][i], type: WidthType.DXA },
    shading: { type: ShadingType.CLEAR, fill: ACCENT },
    margins: { top: 80, bottom: 80, left: 100, right: 100 },
    children: [new Paragraph({ children: [new TextRun({ text: t, bold: true, size: 18, color: "FFFFFF", font: "Arial" })] })]
  }))});
  const dataRows = rows.map(([c1,c2,c3], i) => new TableRow({ children: [c1,c2,c3].map((v,j)=> new TableCell({
    borders, width: { size: [w1,w2,w3][j], type: WidthType.DXA },
    shading: { type: ShadingType.CLEAR, fill: i%2===0?"F5F3FF":"FFFFFF" },
    margins: { top: 70, bottom: 70, left: 100, right: 100 },
    children: [new Paragraph({ children: [new TextRun({ text: v, size: 18, color: MID_GRAY, font: "Arial" })] })]
  }))}));
  return new Table({ width: { size: W, type: WidthType.DXA }, columnWidths: [w1,w2,w3], rows: [hRow, ...dataRows] });
}

function rule() {
  return new Paragraph({ spacing: sp(160,160), border: { bottom: { style: BorderStyle.SINGLE, size: 4, color: "C7D2FE" } }, children: [] });
}

